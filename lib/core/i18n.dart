import 'package:flutter/widgets.dart';

/// Lightweight localisation for the app chrome and the course workflow.
///
/// Strings missing from a language fall back to English, so a new key never
/// breaks a screen.
enum AppLanguage { en, it, es, fr, de, zh, ja, ru }

extension AppLanguageX on AppLanguage {
  String get code => name;
  String get label => switch (this) {
        AppLanguage.en => 'English',
        AppLanguage.it => 'Italiano',
        AppLanguage.es => 'Español',
        AppLanguage.fr => 'Français',
        AppLanguage.de => 'Deutsch',
        AppLanguage.zh => '中文',
        AppLanguage.ja => '日本語',
        AppLanguage.ru => 'Русский',
      };
  Locale get locale => Locale(code);
}

AppLanguage languageFromCode(String? code) {
  for (final l in AppLanguage.values) {
    if (l.code == code) return l;
  }
  return AppLanguage.en;
}

class L {
  L._(this.language);
  final AppLanguage language;

  static AppLanguage current = AppLanguage.en;

  static L of(BuildContext context) => L._(current);

  /// Translation without a context, for services and tests.
  static String tr(String key) =>
      _strings[current]?[key] ?? _strings[AppLanguage.en]![key] ?? key;

  String t(String key) =>
      _strings[language]?[key] ?? _strings[AppLanguage.en]![key] ?? key;

  String get dir => 'ltr';
}

